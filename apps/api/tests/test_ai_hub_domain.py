def test_user_credential_instantiation():
    """Verify UserCredential instantiation with masked key and project scope."""
    scope = ProjectScope(scope_id="proj-user-1", scope_type=ScopeType.USER_DECLARED_PROJECT)
    cred = UserCredential(
        id="cred_gemini_01",
        user_id="user_test_123",
        provider=ProviderType.GEMINI,
        friendly_name="Personal Gemini",
        encrypted_api_key="v1:fake_iv:fake_tag:fake_cipher",
        masked_key="AIzaSy...4X9q",
        project_scope=scope,
        cost_tier=CredentialTier.FREE_TIER,
        health_status=CredentialHealth.HEALTHY,
    )
    assert cred.id == "cred_gemini_01"
    assert cred.masked_key == "AIzaSy...4X9q"
    assert cred.cost_tier == CredentialTier.FREE_TIER
    assert cred.is_active
    assert not cred.project_scope.verified
