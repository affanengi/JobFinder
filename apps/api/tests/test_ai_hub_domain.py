def test_model_descriptor_capability_satisfaction():
    """Verify capability subset matching on model descriptors."""
    model = ModelDescriptor(
        model_id="gemini-3.5-flash",
        provider=ProviderType.GEMINI,
        display_name="Gemini 3.5 Flash",
        capabilities={
            ModelCapability.STRUCTURED_OUTPUT,
            ModelCapability.LONG_CONTEXT,
            ModelCapability.FAST_INFERENCE,
        },
        context_window=1000000,
        cost_tier=CostTier.FREE,
    )

    # Subsets match
    assert model.satisfies_capabilities({ModelCapability.STRUCTURED_OUTPUT})
    assert model.satisfies_capabilities(
        {ModelCapability.STRUCTURED_OUTPUT, ModelCapability.LONG_CONTEXT}
    )

    # Missing capability does not match
    assert not model.satisfies_capabilities({ModelCapability.HIGH_REASONING})


