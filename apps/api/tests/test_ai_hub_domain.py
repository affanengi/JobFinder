def test_project_scope_unverified_never_provably_independent():
    """Verify that UNVERIFIED_UNIQUE and USER_DECLARED_PROJECT scopes are NEVER treated as proof of quota independence."""
    # Synthetic scopes generated by system
    synth_a = ProjectScope(
        scope_id="synth_key_a", scope_type=ScopeType.UNVERIFIED_UNIQUE, verified=False
    )
    synth_b = ProjectScope(
        scope_id="synth_key_b", scope_type=ScopeType.UNVERIFIED_UNIQUE, verified=False
    )

    # Different IDs, but unverified -> CANNOT prove independence
    assert not synth_a.is_provably_independent(synth_b)
    assert not synth_b.is_provably_independent(synth_a)

    # User declared scopes (e.g. user typed "Project A" and "Project B")
    user_decl_a = ProjectScope(
        scope_id="Project A", scope_type=ScopeType.USER_DECLARED_PROJECT, verified=False
    )
    user_decl_b = ProjectScope(
        scope_id="Project B", scope_type=ScopeType.USER_DECLARED_PROJECT, verified=False
    )

    # Different IDs, but user-declared -> CANNOT prove independence
    assert not user_decl_a.is_provably_independent(user_decl_b)
    assert not user_decl_a.is_provably_independent(synth_a)


def test_project_scope_verified_establishes_genuine_boundary():
    """Verify that only provider-verified scopes establish genuine quota independence."""
    verified_proj_1 = ProjectScope(
        scope_id="gcp-project-100", scope_type=ScopeType.VERIFIED_PROJECT, verified=True
    )
    verified_proj_2 = ProjectScope(
        scope_id="gcp-project-200", scope_type=ScopeType.VERIFIED_PROJECT, verified=True
    )
    verified_proj_1_clone = ProjectScope(
        scope_id="gcp-project-100", scope_type=ScopeType.VERIFIED_PROJECT, verified=True
    )

    # Different verified projects are provably independent
    assert verified_proj_1.is_provably_independent(verified_proj_2)
    assert verified_proj_2.is_provably_independent(verified_proj_1)

    # Same project is NOT independent
    assert not verified_proj_1.is_provably_independent(verified_proj_1_clone)


def test_project_scope_shares_known_scope():
    """Verify detection of explicitly identical scopes."""
    scope_a1 = ProjectScope(scope_id="project-shared", scope_type=ScopeType.USER_DECLARED_PROJECT)
    scope_a2 = ProjectScope(scope_id="project-shared", scope_type=ScopeType.USER_DECLARED_PROJECT)
    scope_b = ProjectScope(scope_id="project-other", scope_type=ScopeType.USER_DECLARED_PROJECT)

    assert scope_a1.shares_known_scope(scope_a2)
    assert not scope_a1.shares_known_scope(scope_b)


def test_cost_policy_free_only():
    """Verify FREE_ONLY allows strictly free resources and blocks paid or unknown resources."""
    # Free model on free credential -> ALLOWED
    res_free = evaluate_cost_policy(
        policy=CostPolicy.FREE_ONLY,
        allow_paid_fallback=False,
        model_tier=CostTier.FREE,
        credential_tier=CredentialTier.FREE_TIER,
    )
    assert res_free.allowed
    assert res_free.effective_tier == CostTier.FREE

    # Paid model -> BLOCKED
    res_paid = evaluate_cost_policy(
        policy=CostPolicy.FREE_ONLY,
        allow_paid_fallback=False,
        model_tier=CostTier.PAID,
        credential_tier=CredentialTier.FREE_TIER,
    )
    assert not res_paid.allowed
    assert res_paid.effective_tier == CostTier.PAID
    assert "violates FREE_ONLY policy" in (res_paid.rejection_reason or "")

    # Unknown model -> BLOCKED (defensively treated as PAID)
    res_unknown = evaluate_cost_policy(
        policy=CostPolicy.FREE_ONLY,
        allow_paid_fallback=False,
        model_tier=CostTier.UNKNOWN,
        credential_tier=CredentialTier.FREE_TIER,
    )
    assert not res_unknown.allowed
    assert res_unknown.effective_tier == CostTier.PAID

    # Free model on PAID_TIER credential -> BLOCKED
    res_paid_cred = evaluate_cost_policy(
        policy=CostPolicy.FREE_ONLY,
        allow_paid_fallback=False,
        model_tier=CostTier.FREE,
        credential_tier=CredentialTier.PAID_TIER,
    )
    assert not res_paid_cred.allowed


def test_cost_policy_free_preferred():
    """Verify FREE_PREFERRED respects allow_paid_fallback flag."""
    # Free model is always allowed
    res_free = evaluate_cost_policy(
        policy=CostPolicy.FREE_PREFERRED,
        allow_paid_fallback=False,
        model_tier=CostTier.FREE,
        credential_tier=CredentialTier.FREE_TIER,
    )
    assert res_free.allowed
    assert res_free.effective_tier == CostTier.FREE

    # Paid model when allow_paid_fallback=False -> BLOCKED
    res_paid_blocked = evaluate_cost_policy(
        policy=CostPolicy.FREE_PREFERRED,
        allow_paid_fallback=False,
        model_tier=CostTier.PAID,
        credential_tier=CredentialTier.PAID_TIER,
    )
    assert not res_paid_blocked.allowed
    assert "allowPaidFallback is disabled" in (res_paid_blocked.rejection_reason or "")

    # Paid model when allow_paid_fallback=True -> ALLOWED
    res_paid_allowed = evaluate_cost_policy(
        policy=CostPolicy.FREE_PREFERRED,
        allow_paid_fallback=True,
        model_tier=CostTier.PAID,
        credential_tier=CredentialTier.PAID_TIER,
    )
    assert res_paid_allowed.allowed
    assert res_paid_allowed.effective_tier == CostTier.PAID


