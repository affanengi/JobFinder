class MockAdapter(BaseProviderAdapter):
    """Configurable mock adapter for routing and fallback tests."""

    def __init__(self, provider: ProviderType, models: list[ModelDescriptor]):
        self._provider = provider
        self._models = models

    @property
    def provider_type(self) -> ProviderType:
        return self._provider

    def get_supported_models(self) -> list[ModelDescriptor]:
        return self._models

    def classify_error(self, error: Exception, model: str) -> AIProviderError:
        if isinstance(error, AIProviderError):
            return error
        return AIProviderError(str(error), model=model)

    async def generate_text(
        self,
        model: str,
        prompt: str,
        system_instruction: str | None = None,
        temperature: float = 0.7,
        timeout: float = 30.0,
        **kwargs,
    ) -> str:
        return f"Generated by {model}"

    async def generate_structured(
        self,
        model: str,
        prompt: str,
        schema: type[T],
        system_instruction: str | None = None,
        temperature: float = 0.1,
        timeout: float = 30.0,
        **kwargs,
    ) -> tuple[str, T]:
        return ("{}", schema())

    async def embed(
        self,
        text: str,
        model: str | None = None,
        max_retries: int = 1,
        base_delay_seconds: float = 0.5,
        **kwargs,
    ) -> list[float]:
        return [0.1, 0.2, 0.3]


