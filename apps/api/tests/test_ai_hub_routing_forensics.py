def test_cursor_pagination_telemetry(clean_telemetry):
    """Verify cursor-based pagination returns correct pages and next_cursor."""
    user_id = "user_page_test"

    # Seed 5 records with explicit timestamps
    for i in range(1, 6):
        ai_telemetry_repo.record_execution(
            user_id=user_id,
            record={
                "executionId": f"exec_{i}",
                "userId": user_id,
                "task": "resume_tailoring",
                "providerUsed": "GEMINI",
                "modelUsed": "gemini-3.5-flash",
                "credentialIdUsed": "cred_1",
                "success": True,
                "latencyMs": 100.0 * i,
                "fallbackLevel": 0,
                "hopsCount": 1,
                "timestamp": f"2026-10-05T10:0{i}:00+00:00",
            },
        )

    # Page 1: limit 2
    page1 = ai_telemetry_repo.list_executions_paginated(user_id, limit=2)
    assert len(page1["items"]) == 2
    assert page1["items"][0]["executionId"] == "exec_5"
    assert page1["items"][1]["executionId"] == "exec_4"
    assert page1["has_more"] is True
    assert page1["next_cursor"] == "2026-10-05T10:04:00+00:00"

    # Page 2: limit 2 with cursor from Page 1
    page2 = ai_telemetry_repo.list_executions_paginated(user_id, limit=2, cursor=page1["next_cursor"])
    assert len(page2["items"]) == 2
    assert page2["items"][0]["executionId"] == "exec_3"
    assert page2["items"][1]["executionId"] == "exec_2"
    assert page2["has_more"] is True
    assert page2["next_cursor"] == "2026-10-05T10:02:00+00:00"

    # Page 3: limit 2 with cursor from Page 2
    page3 = ai_telemetry_repo.list_executions_paginated(user_id, limit=2, cursor=page2["next_cursor"])
    assert len(page3["items"]) == 1
    assert page3["items"][0]["executionId"] == "exec_1"
    assert page3["has_more"] is False
    assert page3["next_cursor"] is None
