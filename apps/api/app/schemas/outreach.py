"""Schemas for Outreach Generation, Truth-Lock Verification, and Sending Lifecycle."""

from datetime import UTC, datetime
from typing import Literal
from pydantic import BaseModel, Field

from app.schemas.opportunity_contact import EmailEvidenceClassification

OutreachStatus = Literal[
    "DRAFT",
    "PENDING_APPROVAL",
    "APPROVED",
    "SENDING",
    "SENT",
    "SEND_FAILED",
    "SEND_STATUS_UNKNOWN",
]


class TruthLockFinding(BaseModel):
    """Specific finding from Truth-Lock validation of an outreach claim."""

    status: Literal["PASS", "FAIL", "REVIEW_REQUIRED"]
    field: str
    claim: str
    reason: str
    isBlocking: bool = False


class TruthLockReport(BaseModel):
    """Comprehensive Truth-Lock audit report verifying draft claims against verified profile facts."""

    status: Literal["PASS", "REVIEW_REQUIRED", "FAIL"]
    totalChecks: int = 0
    passedChecks: int = 0
    findings: list[TruthLockFinding] = Field(default_factory=list)
    verifiedFactReferences: list[str] = Field(default_factory=list)


class AIGeneratedOutreach(BaseModel):
    """Structured Pydantic response generated by Gemini AI Hub."""

    subject: str
    body: str
    citedFacts: list[str] = Field(default_factory=list)
    contactRoleRelevance: str = ""


class OutreachMessage(BaseModel):
    """Authoritative persistent record of an outreach email draft and sending lifecycle."""

    id: str
    userId: str
    opportunityId: str
    contactId: str
    recipientEmail: str | None = None
    recipientName: str
    recipientTitle: str | None = None
    companyName: str
    emailClassification: EmailEvidenceClassification = "UNVERIFIED"
    subject: str
    body: str
    status: OutreachStatus = "DRAFT"
    truthLockReport: TruthLockReport = Field(default_factory=lambda: TruthLockReport(status="PASS"))
    resumeAttachmentId: str | None = None
    resumeAttachmentName: str | None = None
    gmailMessageId: str | None = None
    gmailThreadId: str | None = None
    sentAt: str | None = None
    sendError: str | None = None
    correlationId: str
    lastReplyAt: str | None = None
    lastReplyIntent: str | None = None
    replyCount: int = 0
    createdAt: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())
    updatedAt: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())


ReplyIntentLabel = Literal[
    "POSITIVE_INTEREST",
    "INFORMATION_REQUEST",
    "REFERRAL_CONFIRMED",
    "JOB_REJECTION",
    "DO_NOT_CONTACT",
    "NEEDS_MANUAL_REVIEW",
]


class ReplyClassificationResult(BaseModel):
    """Structured Pydantic response generated by Gemini AI Hub for intent classification."""

    intent: ReplyIntentLabel
    confidence: float = Field(default=0.9, ge=0.0, le=1.0)
    rationale: str
    suggestedSuppression: Literal["NONE", "JOB_SPECIFIC_SUPPRESSION", "GLOBAL_STAKEHOLDER_SUPPRESSION"] = "NONE"
    evidenceSnippet: str = ""


class OutreachReply(BaseModel):
    """Authoritative persistent record of an inbound reply to JobFinder outreach."""

    id: str
    outreachId: str
    userId: str
    opportunityId: str
    contactId: str
    gmailMessageId: str
    gmailThreadId: str
    senderEmail: str
    senderName: str | None = None
    recipientEmail: str
    subject: str
    snippet: str
    bodyText: str
    receivedAt: str
    intent: ReplyIntentLabel = "NEEDS_MANUAL_REVIEW"
    intentRationale: str = ""
    intentConfidence: float = 0.0
    evidenceSnippet: str = ""
    processingStatus: Literal["PENDING", "CLASSIFIED", "CLASSIFICATION_FAILED", "MANUALLY_REVIEWED"] = "PENDING"
    suppressionState: Literal["NONE", "JOB_SPECIFIC_SUPPRESSION", "GLOBAL_STAKEHOLDER_SUPPRESSION"] = "NONE"
    isManuallyReviewed: bool = False
    manualNotes: str | None = None
    createdAt: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())
    updatedAt: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())


class ManualReviewReplyRequest(BaseModel):
    """Payload to submit manual review correction for a reply."""

    intent: ReplyIntentLabel
    notes: str | None = None
    overrideSuppression: Literal["NONE", "JOB_SPECIFIC_SUPPRESSION", "GLOBAL_STAKEHOLDER_SUPPRESSION"] | None = None


class ThreadTimelineResponse(BaseModel):
    """Aggregated timeline view of outreach and all replies."""

    outreach: OutreachMessage
    replies: list[OutreachReply] = Field(default_factory=list)
    totalReplies: int = 0
    hasReadPermission: bool = True


class SyncRepliesResponse(BaseModel):
    """Response returned after syncing replies for an outreach message or opportunity."""

    outreachId: str | None = None
    newRepliesCount: int = 0
    totalRepliesCount: int = 0
    replies: list[OutreachReply] = Field(default_factory=list)
    hasReadPermission: bool = True
    message: str


class GenerateOutreachRequest(BaseModel):
    """Request payload to generate personalized, Truth-Locked outreach draft."""

    notes: str | None = None
    tone: Literal["professional", "enthusiastic", "concise"] = "concise"
    resumeAttachmentId: str | None = None


class SaveOutreachDraftRequest(BaseModel):
    """Request payload to manually edit and save an outreach draft."""

    subject: str
    body: str
    resumeAttachmentId: str | None = None


class ApproveOutreachRequest(BaseModel):
    """Request payload to explicitly approve a draft for sending."""

    isApproved: bool = True


class SendOutreachResponse(BaseModel):
    """Response payload following send or send attempt."""

    outreachId: str
    status: OutreachStatus
    gmailMessageId: str | None = None
    correlationId: str
    message: str
